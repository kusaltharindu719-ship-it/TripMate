  user_id uuid primary key
    references public.profiles(id)
    on delete cascade,

  in_app_enabled boolean not null default true,

  email_enabled boolean not null default false,

  push_enabled boolean not null default false,

  booking_updates boolean not null default true,

  driver_bid_updates boolean not null default true,

  verification_updates boolean not null default true,

  review_updates boolean not null default true,

  trip_reminders boolean not null default true,

  service_reminders boolean not null default true,

  updated_at timestamptz not null default now()
);


drop trigger if exists
set_notification_preferences_updated_at
on public.notification_preferences;

create trigger
set_notification_preferences_updated_at
before update
on public.notification_preferences
for each row
execute procedure public.set_updated_at();



-- =========================================================
-- 6. AUTO-CREATE NOTIFICATION PREFERENCES
-- FOR NEW PROFILE ROWS
-- =========================================================

create or replace function
public.create_default_notification_preferences()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin

  insert into public.notification_preferences (
    user_id
  )
  values (
    new.id
  )
  on conflict (user_id) do nothing;


  return new;

end;
$$;


drop trigger if exists
create_default_notification_preferences_trigger
on public.profiles;

create trigger
create_default_notification_preferences_trigger
after insert
on public.profiles
for each row
execute procedure
public.create_default_notification_preferences();




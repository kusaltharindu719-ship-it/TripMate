-- 10. REFINE EXISTING FOOD ITEMS
-- =========================================================

alter table public.food_items
  add column if not exists category_id bigint,
  add column if not exists currency text not null default 'LKR',
  add column if not exists preparation_minutes integer,
  add column if not exists updated_at timestamptz not null default now();


-- Convert any existing text categories into category records
insert into public.food_categories (
  restaurant_id,
  name
)
select distinct
  restaurant_id,
  trim(category)
from public.food_items
where category is not null
  and trim(category) <> ''
on conflict (restaurant_id, name)
do nothing;


-- Link existing food items to their new category
update public.food_items fi
set category_id = fc.id
from public.food_categories fc
where fi.category_id is null
  and fi.category is not null
  and fi.restaurant_id = fc.restaurant_id
  and trim(fi.category) = fc.name;


-- Add foreign key only if it does not already exist
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'food_items_category_id_fkey'
  ) then
    alter table public.food_items
      add constraint food_items_category_id_fkey
      foreign key (category_id)
      references public.food_categories(id)
      on delete set null;
  end if;
end $$;


-- Validate preparation time
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'food_items_preparation_minutes_check'
  ) then
    alter table public.food_items
      add constraint food_items_preparation_minutes_check
      check (
        preparation_minutes is null
        or preparation_minutes >= 0

-- 1. REFINE EXISTING RESTAURANTS TABLE
-- =========================================================

alter table public.restaurants
  add column if not exists email text,
  add column if not exists price_range text,
  add column if not exists accepts_reservations boolean not null default true,
  add column if not exists average_preparation_minutes integer,
  add column if not exists updated_at timestamptz not null default now();


-- Validate price range
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'restaurants_price_range_check'
  ) then
    alter table public.restaurants
      add constraint restaurants_price_range_check
      check (
        price_range is null
        or price_range in (
          'budget',
          'moderate',
          'premium',
          'luxury'
        )
      );
  end if;
end $$;


-- Validate preparation time
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'restaurants_preparation_time_check'
  ) then
    alter table public.restaurants
      add constraint restaurants_preparation_time_check
      check (
        average_preparation_minutes is null
        or average_preparation_minutes >= 0
      );
  end if;
end $$;




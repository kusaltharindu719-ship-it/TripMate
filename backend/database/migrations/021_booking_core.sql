-- =========================================================
-- 7. AUTOMATIC BOOKING STATUS AUDIT
-- =========================================================

create or replace function public.log_booking_status_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin

  if tg_op = 'INSERT' then

    insert into public.booking_status_history (
      booking_id,
      old_status,
      new_status,
      changed_by
    )
    values (
      new.id,
      null,
      new.status,
      auth.uid()
    );


  elsif new.status is distinct from old.status then

    insert into public.booking_status_history (
      booking_id,
      old_status,
      new_status,
      changed_by
    )
    values (
      new.id,
      old.status,
      new.status,
      auth.uid()
    );

  end if;


  return new;
end;
$$;


drop trigger if exists log_booking_status_change_trigger
on public.bookings;

create trigger log_booking_status_change_trigger
after insert or update of status
on public.bookings
for each row
execute procedure public.log_booking_status_change();



-- =========================================================
-- 8. CANCELLATION FOUNDATION
--
-- Can represent:
--   full booking cancellation
--   single booking-item cancellation
--
-- Refund processing will be handled separately later.
-- =========================================================

create table if not exists public.booking_cancellations (
  id bigint generated by default as identity primary key,

  booking_id bigint not null
    references public.bookings(id)
    on delete cascade,

  booking_item_id bigint
    references public.booking_items(id)
    on delete cascade,

  requested_by uuid not null
    references public.profiles(id)
    on delete restrict,

  cancellation_type text not null
    check (
      cancellation_type in (
        'full_booking',
        'booking_item'
      )
    ),

  reason text,

  status text not null default 'requested'
    check (
      status in (
        'requested',
        'approved',
        'rejected',
        'processed'
      )
    ),

  refund_amount numeric(14,2)
    check (
      refund_amount is null
      or refund_amount >= 0
    ),

  requested_at timestamptz not null default now(),
  reviewed_at timestamptz,
  processed_at timestamptz,

  check (
    (
      cancellation_type = 'full_booking'
      and booking_item_id is null
    )
    or
    (
      cancellation_type = 'booking_item'
      and booking_item_id is not null
    )
  )
);


create index if not exists booking_cancellations_booking_idx
on public.booking_cancellations(booking_id);


create index if not exists booking_cancellations_item_idx
on public.booking_cancellations(booking_item_id)
where booking_item_id is not null;



-- =========================================================
-- 9. BASIC DATA-INTEGRITY TRIGGER
--
-- Prevent cancellation request from referencing an item
-- that belongs to another booking.
-- =========================================================

create or replace function public.validate_booking_cancellation_item()
returns trigger
language plpgsql
set search_path = ''
as $$
begin

  if new.booking_item_id is not null then

    if not exists (
      select 1
      from public.booking_items bi
      where bi.id = new.booking_item_id
        and bi.booking_id = new.booking_id
    ) then

      raise exception
        'Booking item does not belong to this booking';

    end if;

  end if;


  return new;
end;
$$;


drop trigger if exists
validate_booking_cancellation_item_trigger
on public.booking_cancellations;

create trigger
validate_booking_cancellation_item_trigger
before insert or update
on public.booking_cancellations
for each row
execute procedure
public.validate_booking_cancellation_item();




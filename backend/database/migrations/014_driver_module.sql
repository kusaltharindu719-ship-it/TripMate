begin

  if not exists (
    select 1
    from pg_constraint
    where conname = 'transport_requests_selected_bid_fk'
  ) then

    alter table public.transport_requests
    add constraint transport_requests_selected_bid_fk
    foreign key (selected_bid_id)
    references public.driver_bids(id)
    on delete set null;

  end if;

end
$$;



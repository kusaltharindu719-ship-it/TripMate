-- =========================================================
-- 15. BID VALIDATION
-- =========================================================

create or replace function public.validate_driver_bid()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  request_record record;
  driver_record record;
  vehicle_record record;
begin

  -- Full validation is required while bid is active/pending
  if new.status <> 'pending' then
    return new;
  end if;


  select
    tr.status,
    tr.bidding_deadline,
    tr.passenger_count,
    tr.luggage_count,
    tr.trip_start_date,
    tr.trip_end_date,
    tr.currency
  into request_record
  from public.transport_requests tr
  where tr.id = new.transport_request_id;


  if not found then
    raise exception 'Transport request does not exist';
  end if;


  if request_record.status <> 'open' then
    raise exception 'Transport request is not open for bidding';
  end if;


  if request_record.bidding_deadline is null
     or request_record.bidding_deadline <= now() then
    raise exception 'Bidding deadline has passed';
  end if;


  -- Driver account must be approved
  if not public.is_provider_approved(
    new.driver_id,
    'driver'
  ) then
    raise exception 'Driver is not approved';
  end if;


  select
    dp.is_accepting_requests,
    dl.expiry_date
  into driver_record
  from public.driver_profiles dp
  left join public.driver_licenses dl
    on dl.driver_id = dp.user_id
  where dp.user_id = new.driver_id;


  if not found then
    raise exception 'Driver profile does not exist';
  end if;


  if driver_record.is_accepting_requests is not true then
    raise exception 'Driver is not accepting trip requests';
  end if;


  if driver_record.expiry_date is null then
    raise exception 'Driver licence information is required';
  end if;


  -- Licence must remain valid for the entire trip
  if driver_record.expiry_date < request_record.trip_end_date then
    raise exception 'Driver licence expires before trip completion';
  end if;


  -- Vehicle must belong to this driver and be approved
  select
    v.passenger_capacity,
    v.luggage_capacity,
    v.is_active,
    vv.status as verification_status
  into vehicle_record
  from public.vehicles v
  left join public.vehicle_verifications vv
    on vv.vehicle_id = v.id
  where v.id = new.vehicle_id
    and v.driver_id = new.driver_id;


  if not found then
    raise exception 'Vehicle does not belong to this driver';
  end if;


  if vehicle_record.is_active is not true then
    raise exception 'Vehicle is inactive';
  end if;


  if vehicle_record.verification_status is distinct from 'approved' then
    raise exception 'Vehicle is not approved';
  end if;


  if vehicle_record.passenger_capacity
     < request_record.passenger_count then
    raise exception 'Vehicle does not have enough passenger capacity';
  end if;


  if vehicle_record.luggage_capacity
     < request_record.luggage_count then
    raise exception 'Vehicle does not have enough luggage capacity';
  end if;


  -- Block bids where driver is marked unavailable/booked
  -- during any date in the requested trip.
  if exists (
    select 1
    from public.driver_availability da
    where da.driver_id = new.driver_id
      and da.availability_date
          between request_record.trip_start_date
          and request_record.trip_end_date
      and da.status in (
        'unavailable',
        'booked'
      )
  ) then
    raise exception 'Driver is unavailable during requested trip dates';
  end if;


  -- Client does not choose bid currency or expiry.
  new.currency :=
    request_record.currency;

  new.expires_at :=
    request_record.bidding_deadline;


  return new;
end;
$$;


drop trigger if exists validate_driver_bid_trigger
on public.driver_bids;

create trigger validate_driver_bid_trigger
before insert or update
on public.driver_bids
for each row
execute procedure public.validate_driver_bid();




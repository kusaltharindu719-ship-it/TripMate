-- Automatically create pickup + destination snapshots
create or replace function public.create_transport_request_stops()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin

  -- Pickup
  insert into public.transport_request_stops (
    transport_request_id,
    stop_order,
    stop_type,
    location_name,
    latitude,
    longitude,
    planned_departure_date
  )
  values (
    new.id,
    0,
    'pickup',
    new.pickup_location_snapshot,
    new.pickup_latitude,
    new.pickup_longitude,
    new.trip_start_date
  );


  -- Destinations
  insert into public.transport_request_stops (
    transport_request_id,
    stop_order,
    stop_type,
    location_name,
    latitude,
    longitude,
    planned_arrival_date,
    planned_departure_date
  )
  select
    new.id,
    td.visit_order,
    'destination',
    d.name,
    d.latitude,
    d.longitude,
    td.planned_arrival_date,
    td.planned_departure_date
  from public.trip_destinations td
  join public.destinations d
    on d.id = td.destination_id
  where td.trip_id = new.trip_id
  order by td.visit_order;


  return new;
end;
$$;


drop trigger if exists create_transport_request_stops_trigger
on public.transport_requests;

create trigger create_transport_request_stops_trigger
after insert
on public.transport_requests
for each row
execute procedure public.create_transport_request_stops();




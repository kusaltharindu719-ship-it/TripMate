-- =========================================================
-- 12. COPY AUTHORITATIVE TRIP DATA INTO REQUEST SNAPSHOT
-- =========================================================

create or replace function public.populate_transport_request_snapshot()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  trip_record record;
begin

  if tg_op = 'UPDATE'
     and new.trip_id is distinct from old.trip_id then
    raise exception 'Transport request trip cannot be changed';
  end if;


  if tg_op = 'INSERT' then

    select
      t.traveler_id,
      t.start_location,
      t.start_lat,
      t.start_lng,
      t.start_date,
      t.end_date,
      t.number_of_travelers,
      t.special_requirements,
      t.currency
    into trip_record
    from public.trips t
    where t.id = new.trip_id;


    if not found then
      raise exception 'Trip does not exist';
    end if;


    if not exists (
      select 1
      from public.trip_destinations td
      where td.trip_id = new.trip_id
    ) then
      raise exception 'Trip must contain at least one destination before requesting transport';
    end if;


    new.traveler_id :=
      trip_record.traveler_id;

    new.pickup_location_snapshot :=
      trip_record.start_location;

    new.pickup_latitude :=
      trip_record.start_lat;

    new.pickup_longitude :=
      trip_record.start_lng;

    new.trip_start_date :=
      trip_record.start_date;

    new.trip_end_date :=
      trip_record.end_date;

    new.passenger_count :=
      trip_record.number_of_travelers;

    new.special_requirements :=
      trip_record.special_requirements;

    new.currency :=
      coalesce(trip_record.currency, 'LKR');

  end if;


  -- A driver should know route distance and duration
  -- before bidding.
  if new.status = 'open' then

    if new.route_distance_km is null
       or new.estimated_duration_minutes is null then
      raise exception 'Route distance and estimated duration are required before opening transport request';
    end if;


    if new.bidding_deadline is null
       or new.bidding_deadline <= now() then
      raise exception 'A future bidding deadline is required before opening transport request';
    end if;

  end if;


  return new;
end;
$$;


drop trigger if exists populate_transport_request_snapshot_trigger
on public.transport_requests;

create trigger populate_transport_request_snapshot_trigger
before insert or update
on public.transport_requests
for each row
execute procedure public.populate_transport_request_snapshot();




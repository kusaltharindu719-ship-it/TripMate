create table if not exists public.driver_profiles (
  user_id uuid primary key
    references public.profiles(id)
    on delete cascade,

  public_name text not null,
  bio text,

  years_experience integer not null default 0
    check (years_experience >= 0),

  is_accepting_requests boolean not null default false,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- Only users with role = driver can have a driver profile
create or replace function public.validate_driver_profile_role()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_role text;
begin

  select p.role
  into profile_role
  from public.profiles p
  where p.id = new.user_id;

  if profile_role is distinct from 'driver' then
    raise exception 'Only users with driver role can create a driver profile';
  end if;

  return new;
end;
$$;


drop trigger if exists validate_driver_profile_role_trigger
on public.driver_profiles;


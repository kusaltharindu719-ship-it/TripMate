-- =========================================================
-- 2. ADMIN VERIFICATION AUDIT LOG
--
-- Keeps historical evidence of every verification decision.
-- =========================================================

create table if not exists public.verification_audit_log (
  id bigint generated by default as identity primary key,

  admin_id uuid not null
    references public.profiles(id)
    on delete restrict,

  target_user_id uuid
    references public.profiles(id)
    on delete set null,

  entity_type text not null
    check (
      entity_type in (
        'provider_verification',
        'vehicle_verification',
        'driver_document',
        'vehicle_document'
      )
    ),

  entity_id text not null,

  old_status text,
  new_status text not null,

  notes text,

  created_at timestamptz not null default now()
);


create index if not exists
verification_audit_admin_idx
on public.verification_audit_log(
  admin_id,
  created_at desc
);


create index if not exists
verification_audit_entity_idx
on public.verification_audit_log(
  entity_type,
  entity_id,
  created_at desc
);




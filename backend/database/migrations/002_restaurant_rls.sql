"Public can view approved active restaurants"
on public.restaurants;

create policy
"Public can view approved active restaurants"
on public.restaurants

for select
to anon, authenticated

using (

  is_active = true

  and public.is_provider_approved(
    owner_id,
    'restaurant'
  )

);




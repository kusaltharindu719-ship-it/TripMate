-- =========================================================
-- 5. BOOKING PAYMENT STATUS RECONCILIATION
--
-- Existing booking statuses supported:
--
-- unpaid
-- pending
-- paid
-- partially_refunded
-- refunded
-- failed
-- =========================================================

create or replace function
public.reconcile_booking_payment_status(
  p_booking_id bigint
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare

  v_total numeric := 0;

  v_successful_payments numeric := 0;
  v_successful_refunds numeric := 0;

  v_has_pending boolean := false;
  v_has_failed boolean := false;

  v_new_status text;

begin

  select coalesce(b.total_amount, 0)
  into v_total
  from public.bookings b
  where b.id = p_booking_id
  for update;


  if not found then
    raise exception 'Booking does not exist';
  end if;



  select
    coalesce(
      sum(pt.amount)
        filter (
          where pt.status = 'succeeded'
        ),
      0
    ),

    coalesce(
      bool_or(
        pt.status in (
          'pending',
          'processing'
        )
      ),
      false
    ),

    coalesce(
      bool_or(
        pt.status = 'failed'
      ),
      false
    )

  into
    v_successful_payments,
    v_has_pending,
    v_has_failed

  from public.payment_transactions pt

  where pt.booking_id = p_booking_id;



  select
    coalesce(
      sum(pr.amount)
        filter (
          where pr.status = 'succeeded'
        ),
      0
    ),

    (
      v_has_pending
      or
      coalesce(
        bool_or(
          pr.status in (
            'pending',
            'processing'
          )
        ),
        false
      )
    )

  into
    v_successful_refunds,
    v_has_pending

  from public.payment_refunds pr

  where pr.booking_id = p_booking_id;



  if v_successful_payments > 0
     and v_successful_refunds >=
         v_successful_payments then

    v_new_status := 'refunded';


  elsif v_successful_refunds > 0 then

    v_new_status := 'partially_refunded';


  elsif v_total > 0
     and v_successful_payments >=
         v_total then

    v_new_status := 'paid';


  elsif v_has_pending
     or v_successful_payments > 0 then

    -- Existing booking schema does not contain
    -- "partially_paid", therefore partial payment is
    -- represented as pending.
    v_new_status := 'pending';


  elsif v_has_failed then

    v_new_status := 'failed';


  else

    v_new_status := 'unpaid';

  end if;



  update public.bookings
  set payment_status = v_new_status
  where id = p_booking_id
    and payment_status is distinct from v_new_status;


  return v_new_status;

end;
$$;



-- =========================================================
-- 6. AUTOMATIC PAYMENT STATUS SYNC TRIGGER
-- =========================================================

create or replace function
public.sync_booking_payment_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin

  perform public.reconcile_booking_payment_status(
    coalesce(
      new.booking_id,
      old.booking_id
    )
  );

  return coalesce(new, old);

end;
$$;



-- =========================================================
-- 1. PAYMENT TRANSACTIONS
-- =========================================================

create table if not exists public.payment_transactions (

  id bigint
    generated by default as identity
    primary key,

  booking_id bigint not null
    references public.bookings(id)
    on delete restrict,

  traveler_id uuid not null
    references public.profiles(id)
    on delete restrict,

  payment_method text not null
    check (
      payment_method in (
        'pay_later',
        'cash',
        'bank_transfer',
        'online_card'
      )
    ),

  payment_processor text not null
    default 'manual',

  external_reference text,

  idempotency_key text not null unique,

  amount numeric(14,2) not null
    check (amount > 0),

  currency text not null,

  status text not null
    default 'pending'
    check (
      status in (
        'pending',
        'processing',
        'succeeded',
        'failed',
        'cancelled'
      )
    ),

  failure_reason text,

  metadata jsonb not null
    default '{}'::jsonb,

  succeeded_at timestamptz,

  created_at timestamptz not null
    default now(),

  updated_at timestamptz not null
    default now(),

  constraint payment_transaction_idempotency_not_blank
    check (
      length(trim(idempotency_key)) > 0
    ),

  constraint payment_transaction_currency_not_blank
    check (
      length(trim(currency)) > 0
    ),

  constraint payment_processor_not_blank
    check (
      length(trim(payment_processor)) > 0
    )
);


create index if not exists
payment_transactions_booking_idx
on public.payment_transactions(
  booking_id,
  created_at desc
);


create index if not exists
payment_transactions_traveler_idx
on public.payment_transactions(
  traveler_id,
  created_at desc
);


create index if not exists
payment_transactions_status_idx
on public.payment_transactions(
  status,
  created_at desc
);


create unique index if not exists
payment_transactions_external_reference_uidx
on public.payment_transactions(
  payment_processor,
  external_reference
)
where external_reference is not null;



